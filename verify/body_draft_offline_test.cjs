// Local body drafts: persistence, conflict rules and compare-and-delete races.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const code = fs.readFileSync(path.join(__dirname, '..', 'public/js/22b-body-drafts.js'), 'utf8')
  .replace(/^export /gm, '');
const context = vm.createContext({ console, setTimeout, clearTimeout, structuredClone });
vm.runInContext(code + '\nglobalThis.subject = { createBodyDraftSession, createMemoryDraftBackend, bodyDraftMatches };', context);
const { createBodyDraftSession, createMemoryDraftBackend, bodyDraftMatches } = context.subject;
const base = { module: 'writer', bookId: 'a', chapterNo: 1, sourceId: 'v1', baseRevision: 4, baseContent: 'old' };
(async () => {
  let cases = 0;
  const backend = createMemoryDraftBackend();
  const session = createBodyDraftSession({ backend });
  const first = session.capture(base, 'new');
  await session.flush();
  const reopened = createBodyDraftSession({ backend });
  assert.equal((await reopened.list('writer', 'a'))[0].content, 'new'); cases++;
  assert.equal(bodyDraftMatches(first, base), true);
  assert.equal(bodyDraftMatches(first, { ...base, baseRevision: 5 }), false); cases++;
  const novel = { ...base, module: 'novel', sourceId: 'original' };
  const original = session.capture(novel, 'adapted'); await session.flush();
  assert.equal(bodyDraftMatches(original, { ...novel, baseRevision: 99 }), true);
  assert.equal(bodyDraftMatches(original, { ...novel, baseContent: 'changed' }), false);
  assert.equal(bodyDraftMatches(original, { ...novel, sourceExists: false }), false); cases++;
  const newer = session.capture(base, 'newer');
  await session.remove(first);
  assert.equal((await reopened.list('writer', 'a'))[0].content, 'newer'); cases++;
  await session.remove(newer);
  assert.equal((await reopened.list('writer', 'a')).length, 0); cases++;
  session.capture({ ...base, chapterNo: 2 }, 'chapter two');
  session.capture({ ...base, bookId: 'b' }, 'book b');
  session.capture({ ...novel, sourceId: 'adaptation' }, 'other source');
  await session.flush();
  assert.equal((await session.list('novel', 'a')).length, 2);
  assert.equal((await session.list('writer', 'a')).length, 1);
  assert.equal((await session.list('writer', 'b')).length, 1); cases++;
  const long = '中文\n'.repeat(100000);
  session.capture(base, long); await session.flush();
  assert.equal((await session.read(base)).content, long); cases++;
  const statuses = [];
  const broken = createBodyDraftSession({ backend: { ...backend, put: async () => { throw new Error('quota'); } }, onStatus: (s) => statuses.push(s) });
  broken.capture(base, 'must keep');
  assert.equal(await broken.flush(), false);
  assert.equal(broken.hasUnstored(), true);
  assert.equal(statuses.at(-1), 'error'); cases++;
  const prior = session.capture({ ...base, bookId: 'migration' }, 'only durable copy');
  await session.flush();
  broken.capture({ ...base, bookId: 'migration', sourceId: 'v2', baseRevision: 5 }, 'new baseline edit');
  assert.equal(await broken.remove(prior), false);
  assert.equal((await session.list('writer', 'migration'))[0].content, 'only durable copy'); cases++;
  const mixedStatuses = [];
  const mixed = createBodyDraftSession({ backend: { ...backend, put: async row => {
    if (row.sourceId === 'failed') throw new Error('quota');
    await backend.put(row);
  } }, onStatus: status => mixedStatuses.push(status) });
  mixed.capture({ ...base, sourceId: 'failed' }, 'pending failed draft');
  await mixed.flush();
  mixed.capture({ ...base, sourceId: 'successful' }, 'other draft succeeds');
  assert.equal(await mixed.flush(), false);
  assert.equal(mixedStatuses.at(-1), 'error', 'another successful write cannot hide the failed draft'); cases++;
  const readOnly = session.capture({ ...base, readOnly: true }, 'forbidden');
  assert.equal(readOnly, null); cases++;
  let release;
  const delayed = createBodyDraftSession({ backend: { ...backend, put: async (row) => { await new Promise((r) => { release = r; }); await backend.put(row); } } });
  delayed.capture({ ...base, bookId: 'late' }, 'pending');
  while (!release) await Promise.resolve();
  assert.equal(delayed.hasUnstored(), true);
  release(); await delayed.flush();
  assert.equal(delayed.hasUnstored(), false); cases++;
  console.log(`body draft offline: ${cases} cases passed`);
})().catch((error) => { console.error(error); process.exitCode = 1; });
